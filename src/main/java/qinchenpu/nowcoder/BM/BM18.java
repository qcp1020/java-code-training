    public static boolean Find(int target, int[][] array) {
        // write code here
        if (array == null || array.length == 0 || array[0].length == 0)
            return false;

        int rowNum = array.length, colNum = array[0].length;
        int i = rowNum - 1, j = 0;
        while (i >= 0 && j < colNum)
            if (array[i][j] == target)
                return true;
            else if (array[i][j] > target)
                i--;
            else
                j++;
        return false;

    }

