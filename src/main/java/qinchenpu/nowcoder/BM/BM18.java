    public static boolean Find3(int target, int[][] array) {
        // write code here
        int rowNum = array.length, colNum = array[0].length;
        if (array == null || rowNum == 0 || colNum == 0)
            return false;
        for (int i = 0; i < rowNum; i++) {
            int left = 0, right = colNum - 1;
            int j = (left + right) / 2;
            do {
                if (array[i][j] == target)
                    return true;
                else if (array[i][j] > target)
                    right = j - 1;
                else
                    left = j + 1;
                if (right < left) break;
                j = (left + right) / 2;
            } while (j < colNum && j >= 0);

        }
        return false;

    }

